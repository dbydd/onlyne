import { chmod, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";

const PKG_ROOT = resolve(dirname(import.meta.path), "..");

async function buildGuiHtmlAsset(): Promise<void> {
	const cssPath = join(PKG_ROOT, "src/gui/panel.css");
	const appEntry = join(PKG_ROOT, "src/gui/app.ts");
	const outPath = join(PKG_ROOT, "src/gui/assets.generated.ts");

	const css = await readFile(cssPath, "utf8");
	const built = await Bun.build({
		entrypoints: [appEntry],
		target: "browser",
		format: "esm",
		minify: true,
		sourcemap: "none",
	});
	if (!built.success) {
		const msgs = built.logs.map(l => l.message).join("\n");
		throw new Error(`GUI bundle failed:\n${msgs}`);
	}
	const jsText = await built.outputs[0]!.text();
	const safeJs = jsText.replace(/<\/script/gi, "<\\/script");
	const safeCss = css.replace(/<\/style/gi, "<\\/style");

	const html = [
		"<!doctype html>",
		'<html lang="en">',
		"<head>",
		'<meta charset="utf-8" />',
		'<meta name="viewport" content="width=device-width,initial-scale=1" />',
		"<title>Onlyne</title>",
		`<style>${safeCss}</style>`,
		"</head>",
		"<body>",
		'<div id="app">Loading Onlyne...</div>',
		`<script type="module">${safeJs}</script>`,
		"</body>",
		"</html>",
	].join("\n");

	await writeFile(
		outPath,
		`// Generated by scripts/build.ts. Do not edit manually.\nexport const PANEL_HTML = ${JSON.stringify(html)};\n`,
	);
}

async function runTsc(): Promise<void> {
	await rm(join(PKG_ROOT, "dist"), { recursive: true, force: true });
	const proc = Bun.spawn(["bunx", "tsc", "-p", "tsconfig.json"], {
		cwd: PKG_ROOT,
		stdout: "inherit",
		stderr: "inherit",
	});
	const code = await proc.exited;
	if (code !== 0) {
		throw new Error(`tsc failed with exit code ${code}`);
	}
	for (const rel of ["dist/cli/main.js", "dist/mcp/main.js", "dist/hooks/main.js"]) {
		const abs = join(PKG_ROOT, rel);
		const text = await readFile(abs, "utf8").catch(() => undefined);
		if (text !== undefined) {
			if (!text.startsWith("#!")) {
				await writeFile(abs, `#!/usr/bin/env bun\n${text}`);
			}
			await chmod(abs, 0o755);
		}
	}
}

async function buildPluginBundles(): Promise<void> {
	const pluginDist = join(PKG_ROOT, "plugin/dist");
	await rm(pluginDist, { recursive: true, force: true });
	await mkdir(pluginDist, { recursive: true });

	const targets = [
		{ entry: "src/mcp/main.ts", out: "mcp.js" },
		{ entry: "src/hooks/main.ts", out: "hook.js" },
		{ entry: "src/cli/main.ts", out: "cli.js" },
	] as const;

	for (const t of targets) {
		const built = await Bun.build({
			entrypoints: [join(PKG_ROOT, t.entry)],
			target: "bun",
			format: "esm",
			minify: true,
			sourcemap: "none",
		});
		if (!built.success) {
			const msgs = built.logs.map(l => l.message).join("\n");
			throw new Error(`Plugin bundle failed (${t.entry}):\n${msgs}`);
		}
		const raw = await built.outputs[0]!.text();
		const code = raw.startsWith("#!") ? raw : `#!/usr/bin/env bun\n${raw}`;
		const outPath = join(pluginDist, t.out);
		await writeFile(outPath, code);
		await chmod(outPath, 0o755);
	}
}

async function main(): Promise<void> {
	await buildGuiHtmlAsset();
	await runTsc();
	await buildPluginBundles();
}

void main().catch(err => {
	process.stderr.write(`${err instanceof Error ? err.stack ?? err.message : String(err)}\n`);
	process.exit(1);
});
